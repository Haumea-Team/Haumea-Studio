# Writes track_data.h: where SA-MP's tubes (19646-19689) and stunt roads
# (MRoad, 18788-18801) join the next piece, from SA Map Studio's
# roadTubes.js and roadMRoad.js (Mozilla Public License 2.0). Their tables
# come from the tools TBR (Adr1 Tube Connector 1.10) and Road Construction
# 1.0 (adri1).
#

import json
import os
import re
import sys

src = sys.argv[1]


def consts(name):
	text = open(os.path.join(src, name), encoding='utf-8').read()
	text = re.sub(r'//[^\n]*', '', text)
	out = {}
	for m in re.finditer(r'export const (\w+) = ', text):
		start = m.end()
		# The value: a balanced [...] or {...}, or a number.
		if text[start] in '[{':
			depth, i = 0, start
			while True:
				c = text[i]
				if c in '[{': depth += 1
				elif c in ']}':
					depth -= 1
					if depth == 0: break
				i += 1
			value = text[start:i+1]
			value = re.sub(r'(\d+):', r'"\1":', value)	# bare numeric keys
			value = re.sub(r',\s*([\]}])', r'\1', value)
			out[m.group(1)] = json.loads(value)
		else:
			out[m.group(1)] = json.loads(re.match(r'[-\d.]+', text[start:]).group(0))
	return out


tubes = consts('roadTubes.js')
roads = consts('roadMRoad.js')


def f(v):
	return ('%.4f' % v).rstrip('0').rstrip('.') + 'f' if v != int(v) else '%d.0f' % v


def row(r):
	r = list(r) + [0] * (6 - len(r))
	return '{ ' + ', '.join(f(x) for x in r) + ' }'


out = ['// Generated by gen_track_data.py from SA Map Studio\'s roadTubes.js and',
	'// roadMRoad.js (Mozilla Public License 2.0; tables from TBR, Adr1 Tube',
	'// Connector 1.10, and Road Construction 1.0 by adri1); do not edit.', '',
	'#pragma once', '',
	'// A place relative to a piece: offset x y z, then SA-MP Euler rx ry rz (degrees).',
	'struct TrackPlace { float x, y, z, rx, ry, rz; };', '',
	'// The kinds each tube model joins by, and its row in the extras tables.',
	'struct TrackTube { int model; int kinds[2]; int numKinds; int row; };',
	'static const TrackTube trackTubes[] = {']
for model, kinds in tubes['TUBE_TYPES'].items():
	k = kinds + [0] * (2 - len(kinds))
	out.append('\t{ %s, { %d, %d }, %d, %d },' % (model, k[0], k[1], len(kinds), tubes['TUBE_COUNTER'].get(model, -1)))
out.append('};')
rel = tubes['TUBE_REL']
n = len(rel)
out += ['', '// trackTubeAfter[x][y]: a tube of kind y joined after one of kind x.',
	'static const int TRACK_TUBE_KINDS = %d;' % n,
	'static const TrackPlace trackTubeAfter[%d][%d] = {' % (n, n)]
for x in range(n):
	out.append('\t{ ' + ', '.join(row(rel[x][y]) for y in range(len(rel[x]))) + ' },')
out.append('};')
for name, c in (('TUBE_COVERS', 'trackTubeCovers'), ('TUBE_LIGHTS', 'trackTubeLights'),
		('TUBE_SUPPORT_1', 'trackTubePoles'), ('TUBE_SUPPORT_2', 'trackTubeBrackets1'),
		('TUBE_SUPPORT_3', 'trackTubeBrackets2')):
	rows = tubes[name]
	out += ['', '// By a tube\'s row; has = 0: none for it.',
		'static const struct { bool has; TrackPlace at; } %s[%d] = {' % (c, len(rows))]
	for r in rows:
		out.append('\t{ %s, %s },' % ('true' if r else 'false', row(r or [])))
	out.append('};')
out += ['', '// Each stunt road\'s ends: the frame of the end, +X out of the piece.',
	'struct TrackRoad { int model; TrackPlace ends[2]; };', 'static const TrackRoad trackRoads[] = {']
for model, ends in roads['MROAD_ENDS'].items():
	out.append('\t{ %s, { %s, %s } },' % (model, row(ends[0]), row(ends[1])))
out += ['};', '', 'static const int trackRoadLightModels[] = { %s };' % ', '.join(map(str, roads['MROAD_LIGHT_MODELS'])),
	'// Where the lights go on each stunt road.', 'struct TrackRoadLight { int model; float x, y, z; };',
	'static const TrackRoadLight trackRoadLights[] = {']
for model, pts in roads['MROAD_LIGHTS'].items():
	for p in pts:
		out.append('\t{ %s, %s, %s, %s },' % (model, f(p[0]), f(p[1]), f(p[2])))
out += ['};', '']
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'track_data.h'), 'w', encoding='utf-8') as fh:
	fh.write('\n'.join(out))
print('wrote track_data.h (%d tubes, %d kinds, %d roads)' % (len(tubes['TUBE_TYPES']), n, len(roads['MROAD_ENDS'])))
