# gen_wiki_data.py <web>/frontend/docs/scripting/resources
# Writes wiki_data.h from the open.mp wiki's pages: what each PlayerPlaySound
# ID plays (sound-ids.md), each skin's name (skins.md) and what each
# animation shows (animations.md). The Interiors panel has the interiors,
# from the game's own files.
#

import os
import re
import sys

docs = sys.argv[1]


def read(name):
	return open(os.path.join(docs, name), encoding='utf-8').read().splitlines()


def cstr(s):
	return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def clean(s):
	s = s.replace('\\*', '').replace('*', '').replace("''", '"')
	s = re.sub(r'\s+', ' ', s).strip()
	s = s.strip(' -:')
	# Quoted speech keeps its quotes, written the same way every time.
	m = re.fullmatch(r'"\s*(.*?)\s*"', s)
	if m:
		s = '"' + m.group(1) + '"'
	if s.endswith('.') and not s.endswith('..') and s.count('.') == 1:
		s = s[:-1]
	return s[:1].upper() + s[1:] if s and s[0] != '"' else s


# ---- Sounds ----
# Under these headings a line is only what is said or the place's name, so
# the heading says what it is.
SOUND_HEADINGS = {
	'Police Radio': 'Police radio', 'Gym Guy': 'Gym trainer', 'Casino Woman': 'Casino croupier',
	'Boat School': 'Boat school', '0.3d Sound IDs': 'Police radio',
}
sounds = {}
sameAs = {}
heading = ''
inCode = False


def addSound(sid, text):
	text = clean(text)
	if not text or sid in sounds or sid <= 0:
		return
	m = re.fullmatch(r'Same as (\d+)', text, re.I)
	if m:
		sameAs[sid] = int(m.group(1))
		return
	if heading in SOUND_HEADINGS and (text.startswith('"') or text.isupper()):
		if text.isupper():
			text = '"' + text.strip('"').title().replace("'S", "'s") + '"'
		text = SOUND_HEADINGS[heading] + ': ' + text
	sounds[sid] = text


for line in read('sound-ids.md'):
	if line.startswith('#'):
		heading = line.lstrip('#').strip()
		heading = re.sub(r'\s*\(.*\)$', '', heading)
		continue
	if line.startswith('```'):
		inCode = not inCode
		continue
	s = line.strip()
	if s.startswith('- '):
		s = s[2:]
	# | SOUND_NAME | 1002 (music) |
	m = re.fullmatch(r'\|\s*(SOUND_\w+)\s*\|\s*(\d+)\s*(?:\((.*)\))?\s*\|', s)
	if m:
		name = m.group(1)[6:].replace('_', ' ').capitalize()
		addSound(int(m.group(2)), name + (' (' + m.group(3) + ')' if m.group(3) else ''))
		continue
	# "PLACE" - 2000
	m = re.fullmatch(r'("[^"]+")\s*-\s*(\d+)', s)
	if m:
		addSound(int(m.group(2)), m.group(1))
		continue
	# Ranges ("2 - 59 police radio", "5411-5447: ...") name many sounds at once: left out.
	if re.match(r'\d+\s*-\s*\d+\b', s):
		continue
	# "155, 156 plane interior humming"
	m = re.fullmatch(r'(\d+)\s*,\s*(\d+)\s+(.+)', s)
	if m:
		addSound(int(m.group(1)), m.group(3))
		addSound(int(m.group(2)), m.group(3))
		continue
	m = re.fullmatch(r'(\d+)\s*(?:-|:)?\s+(.+)', s)
	if m:
		addSound(int(m.group(1)), m.group(2))

for sid, other in sameAs.items():
	if sid not in sounds and other in sounds:
		sounds[sid] = sounds[other]


# ---- Tables ----
def table(lines):
	rows = []
	for line in lines:
		if not line.startswith('|') or re.match(r'\|\s*-', line):
			continue
		rows.append([c.strip() for c in line.strip().strip('|').split('|')])
	return rows


skins = []
for row in table(read('skins.md')):
	if row[0].isdigit():
		skins.append((int(row[0]), row[2], clean(row[3])))

anims = []
for row in table(read('animations.md')):
	if row[0].isdigit() and len(row) >= 6 and row[5]:
		anims.append((row[1].upper(), row[2].upper(), clean(row[5])))

out = ['// Generated by gen_wiki_data.py from the open.mp wiki (scripting/resources:',
	'// sound-ids, skins, animations); do not edit.', '', '#pragma once', '',
	'struct WikiSound { int id; const char *text; };',
	'struct WikiSkin { int id; const char *model; const char *name; };',
	'struct WikiAnimation { const char *library; const char *name; const char *text; };',
	'',
	'// By ID.', 'static const WikiSound wikiSounds[] = {']
for sid in sorted(sounds):
	out.append('\t{ %d, %s },' % (sid, cstr(sounds[sid])))
out += ['};', '', 'static const WikiSkin wikiSkins[] = {']
for s in skins:
	out.append('\t{ %d, %s, %s },' % (s[0], cstr(s[1]), cstr(s[2])))
out += ['};', '', '// Library and name in capitals, sorted.', 'static const WikiAnimation wikiAnimations[] = {']
for a in sorted(set(anims)):
	out.append('\t{ %s, %s, %s },' % (cstr(a[0]), cstr(a[1]), cstr(a[2])))
out += ['};', '']
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'wiki_data.h'), 'w', encoding='utf-8') as f:
	f.write('\n'.join(out))
print('wrote wiki_data.h (%d sounds, %d skins, %d animations)' %
	(len(sounds), len(skins), len(set(anims))))
